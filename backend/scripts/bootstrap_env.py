"""Create ``backend/.env.dev`` with freshly generated secrets.

Why this exists: a development environment file that is *committed* contains
secrets, and one that is *hand-written* drifts. This generates a usable
configuration in one command — a random 64-hex JWT secret and per-operator salted
password hashes — so no credential ever has to live in git, and the isolation of
each operator's digest is real rather than nominal.

Usage::

    python backend/scripts/bootstrap_env.py                      # writes ./.env.dev
    python backend/scripts/bootstrap_env.py --force              # overwrite
    python backend/scripts/bootstrap_env.py --password custos-demo --operators commander.rao:commander,analyst.nair:analyst
    python backend/scripts/bootstrap_env.py --print               # write nothing, print to stdout

The default password is intentionally the same for every demo operator and is
printed once, at the end, so nobody has to guess it. Change it before any real
deployment: `--password` accepts anything, and the roster is salted per user.
"""

from __future__ import annotations

import argparse
import secrets
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from custos.api.routers.auth import roster_entry  # noqa: E402
from custos.domain.enums import Role  # noqa: E402

TEMPLATE = """# ---------------------------------------------------------------------------
# CUSTOS — development configuration (GENERATED by scripts/bootstrap_env.py)
#
# This file is git-ignored on purpose: it holds a JWT secret and password
# hashes that must not be shared. Regenerate it any time with:
#     python backend/scripts/bootstrap_env.py --force
# ---------------------------------------------------------------------------
CUSTOS_ENVIRONMENT=development
CUSTOS_DATABASE_URL=sqlite+aiosqlite:///./custos_dev.db
CUSTOS_LOG_LEVEL=INFO
CUSTOS_JWT_SECRET={jwt_secret}
CUSTOS_API_KEYS={api_keys}
CUSTOS_OPERATOR_ROSTER={roster}
CUSTOS_SIM_ENSEMBLE_SIZE=24
CUSTOS_CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000
CUSTOS_AI_ENABLED=true
CUSTOS_OLLAMA_BASE_URL=http://127.0.0.1:11434
CUSTOS_OLLAMA_MODEL=qwen2.5:7b-instruct

# Production note: point CUSTOS_DATABASE_URL at PostgreSQL and let the pool do
# the work —
#   CUSTOS_DATABASE_URL=postgresql+psycopg://custos:…@127.0.0.1:5432/custos
#   CUSTOS_DB_POOL_SIZE=20
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate backend/.env.dev with fresh secrets")
    parser.add_argument("--path", default=str(BACKEND / ".env.dev"))
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--print", dest="to_stdout", action="store_true", help="print instead of writing")
    parser.add_argument("--password", default="custos-demo", help="development password for every demo operator")
    parser.add_argument(
        "--operators",
        default="commander.rao:commander,analyst.nair:analyst,viewer.liaison:viewer",
        help="comma-separated subject:role pairs",
    )
    parser.add_argument("--no-ai", action="store_true", help="disable the local model (deterministic phrasing only)")
    args = parser.parse_args()

    entries: list[str] = []
    for spec in args.operators.split(","):
        spec = spec.strip()
        if not spec:
            continue
        subject, _, role_name = spec.partition(":")
        role_name = role_name or "viewer"
        try:
            role = Role(role_name)
        except ValueError:
            print(f"unknown role {role_name!r} for {subject!r}; skipping (valid: {', '.join(r.value for r in Role)})")
            continue
        entries.append(roster_entry(subject, args.password, role))
    if not entries:
        print("no operators configured - nothing to do")
        return 1

    content = TEMPLATE.format(
        jwt_secret=secrets.token_hex(32),
        api_keys=f"{secrets.token_urlsafe(18)}:ingest",
        roster=";".join(entries),
    )
    if args.no_ai:
        content = content.replace("CUSTOS_AI_ENABLED=true", "CUSTOS_AI_ENABLED=false")

    path = Path(args.path)
    if args.to_stdout:
        print(content)
        return 0

    if path.exists() and not args.force:
        print(f"{path} already exists - refusing to overwrite secrets (use --force to regenerate)")
        return 0

    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")
    print(f"  environment : development")
    print(f"  operators   : {', '.join(spec.split(':')[0] for spec in args.operators.split(',') if spec.strip())}")
    print(f"  password    : {args.password}   (per-user salted sha256; change before any real deployment)")
    print("  jwt secret  : generated (64 hex chars, not shown)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
